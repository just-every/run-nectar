import assert from 'node:assert/strict'
import { samlFixture, startSaml, postSaml } from './saml-fixture.mjs'
import { totp } from './mfa.mjs'

const address = n => ['synthetic-nectar-' + n, 'example.test'].join('@')
const cookies = response => response.headers.getSetCookie().map(line => line.split(';')[0]).join('; ')

// One security journey, through actual sessions, signed HTTP assertions, owner
// approval and SCIM. Only the provider edge and audit fault are synthetic.
export async function enterpriseLinkingFlow(h, owner, { onState, approve } = {}) {
  const idp = await samlFixture()
  const settings = { issuer: idp.issuer, entry_point: idp.entry_point, certificate: idp.certificate, role_map: { billing: 'accountant', ops: 'finance' }, revision: 0 }
  let configured = await h.api('sso.configure', owner, settings)
  const scim = async (path = '', { method = 'GET', body, status = 200, token = configured.scim_token } = {}) => {
    const result = await h.raw('/scim/v2/Users' + path, { method, body, headers: { authorization: 'Bearer ' + token } })
    assert.equal(result.status, status, 'SCIM linking door status')
    return status === 204 ? null : result.json()
  }
  const local = async (n, role = 'accountant') => {
    const member = await h.api('access.give', owner, { email: address(n), name: 'Nectar member ' + n, role })
    return { ...member, cookie: await h.signIn(member.email, { requested: true }) }
  }
  const member = await local(101), peer = await local(102)
  const original = await h.api('me', member.cookie), historical = await h.api('audit', owner)
  const operators = await (await h.raw('/auth/operators', { cookie: owner })).json()
  const operator = operators.find(row => row.email === member.email)
  assert.ok(operator?.id)
  const sign = async ({ who = member, link = true, changes = {}, status = 303, concurrent = false } = {}) => {
    const start = await startSaml(h, { path: link ? '/sso/start?link=1' : '/sso/start', cookie: who.cookie })
    const response = idp.sign({ requestId: start.requestId, callback: h.origin + '/sso/acs', audience: h.origin + '/sso/metadata', subject: 'synthetic-nectar-101', email: who.email, ...changes })
    let posted
    if (concurrent) {
      const replies = await Promise.all([postSaml(h, start, response), postSaml(h, start, response)])
      assert.deepEqual(replies.map(row => row.status).sort(), [303, 403], 'Concurrent signed assertion replay yields one proof')
      posted = replies.find(row => row.status === 303)
    } else posted = await postSaml(h, start, response)
    assert.equal(posted.status, status, 'SAML proof status')
    return { start, response, posted, who }
  }
  const finish = async (signed, { who = signed.who, status = 303, binding = signed.start.binding } = {}) => {
    const response = await h.raw(signed.posted.headers.get('location'), { cookie: [binding, who.cookie].filter(Boolean).join('; ') })
    assert.equal(response.status, status, 'Browser and existing-session bound proof completion')
    return cookies(response)
  }
  const pending = async (who = member) => (await h.api('sso-links', owner)).find(row => row.member.member === who.id)
  const fields = row => ({ link: row.id, basis: row.basis })
  assert.equal((await h.raw('/sso/start?link=1')).status, 403, 'A signed-out caller cannot select an account')
  assert.equal((await h.raw('/sso/start?link=1', { cookie: owner })).status, 403, 'Owner provisioning remains refused')
  await sign({ link: false, status: 403 })
  await scim('', { method: 'POST', body: { externalId: 'synthetic-nectar-101', userName: member.email, roles: [{ value: 'billing' }] }, status: 409 })
  assert.equal(await pending(), undefined, 'Email equality alone creates no link')
  await h.api('mfa.policy', owner, { scope: 'roles', roles: ['accountant'] })
  assert.equal((await h.raw('/sso/start?link=1', { cookie: member.cookie })).status, 403, 'A held native session cannot start a linking proof')
  const memberAt = Date.now()
  await h.advanceClock(new Date(memberAt).toISOString())
  const memberFactor = await h.api('mfa.totp.start', member.cookie, { label: 'Existing member factor' })
  await h.api('mfa.totp.confirm', member.cookie, { factor: memberFactor.factor, code: totp(memberFactor.secret, memberAt) })
  await sign({ status: 403 })
  await sign({ changes: { mfa: true } })
  await h.api('mfa.policy', owner, { scope: 'off' })
  await sign({ changes: { role: 'ops' }, status: 403 })
  await sign({ changes: { age: 400000 }, status: 403 })
  await sign({ changes: { authAge: 400000 }, status: 403 })
  const forged = await sign()
  const fresh = await startSaml(h, { path: '/sso/start?link=1', cookie: member.cookie })
  const freshResponse = idp.sign({ requestId: fresh.requestId, callback: h.origin + '/sso/acs', audience: h.origin + '/sso/metadata', subject: 'synthetic-nectar-101', email: member.email })
  const tampered = Buffer.from(Buffer.from(freshResponse, 'base64').toString().replace('>billing<', '>ops<')).toString('base64')
  assert.equal((await postSaml(h, fresh, tampered)).status, 403, 'A forged assertion grants nothing')
  await finish(forged, { who: peer, status: 403 })
  assert.equal(await pending(), undefined, 'Another native session cannot claim the proof')
  const occupied = await scim('', { method: 'POST', body: { externalId: 'synthetic-nectar-occupied', userName: address(103), roles: [{ value: 'billing' }] }, status: 201 })
  await sign({ changes: { subject: occupied.externalId }, status: 403 })
  const customRole = await h.api('role.define', owner, { name: 'Nectar scoped reader', capabilities: ['read.customers'] })
  await h.api('access.give', owner, { email: address(104), name: 'Scoped member', role: 'custom', custom_role: customRole.id })
  const custom = await h.signIn(address(104), { requested: true })
  assert.equal((await h.raw('/sso/start?link=1', { cookie: custom })).status, 403)

  const signed = await sign({ concurrent: true })
  await finish(signed)
  assert.equal((await postSaml(h, signed.start, signed.response)).status, 403, 'The signed assertion is single-use')
  await finish(signed, { status: 403 })
  let request = await pending()
  assert.equal(request.member.member, original.id)
  assert.equal(request.member.operator, operator.id)
  await h.api('sso-links', member.cookie, undefined, 403)
  await h.api('sso.link.approve', peer.cookie, fields(request), 403)
  const agent = await h.api('credential.issue', owner, { name: 'Link refusal agent', scopes: ['prepare'] })
  await h.api('sso.link.approve', { bearer: agent.key }, fields(request), 403)
  await h.api('credential.revoke', owner, { key: agent.id })
  await h.api('sso.link.approve', { bearer: agent.key }, fields(request), 401)
  await h.api('sso.link.approve', owner, fields(request), 403)
  const at = Date.now()
  await h.advanceClock(new Date(at).toISOString())
  const factor = await h.api('mfa.totp.start', owner, { label: 'Link owner factor' })
  await h.api('mfa.totp.confirm', owner, { factor: factor.factor, code: totp(factor.secret, at) })
  await h.advanceClock(new Date(at + 960000).toISOString())
  assert.equal((await h.api('sso.link.approve', owner, fields(request), 403)).error, 'mfa_step_up_required')
  await h.advanceClock(new Date(at).toISOString())
  await h.api('sso.link.approve', owner, { ...fields(request), basis: 'synthetic-nectar-wrong-basis' }, 409)
  await h.rejectAudit('sso.link.approve')
  await h.api('sso.link.approve', owner, fields(request), 500)
  await h.rejectAudit(null)
  assert.equal((await h.api('me', member.cookie)).id, original.id, 'Audit failure rolls back old-session revocation')
  assert.equal((await pending()).id, request.id, 'Audit failure rolls back the binding claim')
  await sign({ link: false, status: 403 })
  assert.equal((await scim('?filter=' + encodeURIComponent(`externalId eq "${request.subject}"`))).Resources[0].active, false, 'A pending link confers no SCIM authority')
  await scim('/' + request.id, { method: 'PATCH', body: { Operations: [{ op: 'replace', path: 'active', value: true }] }, status: 409 })
  await onState?.({ label: 'link-pending', member, request, owner })
  // Mint a native email token before approval; it must not bypass the binding.
  assert.equal((await h.raw('/auth/magic-link', { body: { email: member.email } })).status, 202)
  const priorMail = h.mails.at(-1)
  if (approve) await approve({ request, owner })
  else {
    const results = await Promise.all([0, 1].map(() => h.raw('/api/nectar/sso.link.approve', { cookie: owner, body: fields(request) })))
    assert.deepEqual(results.map(row => row.status).sort(), [200, 409], 'Concurrent approval creates exactly one binding')
  }
  await h.api('sso.link.approve', owner, fields(request), 409)
  await h.api('me', member.cookie, undefined, 401)
  assert.equal((await h.raw('/auth/magic-link', { body: { email: member.email } })).status, 403)
  const oldLink = (priorMail.html + ' ' + priorMail.text).match(/https?:\/\/[^\s"<]*\/auth\/confirm[^\s"<]*/)?.[0]
  assert.ok(oldLink, 'A real previously issued native link exists')
  const confirmUrl = new URL(oldLink.replaceAll('&amp;', '&'))
  const oldConfirmed = await h.raw('/auth/confirm', { body: { token: confirmUrl.searchParams.get('token') } })
  assert.ok([400, 403].includes(oldConfirmed.status) || oldConfirmed.status === 303)
  if (oldConfirmed.status === 303) await h.api('me', cookies(oldConfirmed), undefined, 401)
  const bound = await finish(await sign({ link: false }))
  assert.deepEqual(await h.api('me', bound), original, 'Linking preserves the member, role and capabilities')
  const afterOperators = await (await h.raw('/auth/operators', { cookie: owner })).json()
  assert.equal(afterOperators.find(row => row.email === member.email).id, operator.id, 'Linking preserves operator attribution')
  const audit = await h.api('audit', owner)
  assert.deepEqual(audit.filter(row => row.seq <= historical[0].seq), historical, 'Historical audit attribution stays byte-for-byte intact')
  const approvals = audit.filter(row => row.action === 'sso.link.approve')
  assert.equal(approvals.length, 1)
  assert.equal(approvals[0].subject, member.id)
  assert.equal(JSON.parse(approvals[0].detail).basis, request.basis)
  assert.equal((await scim('/' + request.id)).active, true)
  await onState?.({ label: 'link-approved', member: { ...member, cookie: bound }, request, owner })
  await sign({ who: peer, changes: { subject: request.subject }, status: 403 })

  await h.api('mfa.policy', owner, { scope: 'roles', roles: ['accountant'] })
  await sign({ link: false, status: 403 })
  const strong = await finish(await sign({ link: false, changes: { mfa: true } }))
  assert.ok((await h.api('mfa', strong)).verified_at, 'Actual signed MFA retains its original authentication time')
  const flight = await sign({ link: false, changes: { mfa: true } })
  const began = performance.now()
  await scim('/' + request.id, { method: 'DELETE', status: 204 })
  await h.api('me', bound, undefined, 401)
  await h.api('me', strong, undefined, 401)
  await finish(flight, { status: 403 })
  assert.ok(performance.now() - began < 60000, 'SCIM revocation ends existing and pending sign-ins within a minute')
  await onState?.({ label: 'link-deprovisioned', member, request, owner })
  await scim('/' + request.id, { method: 'PATCH', body: { Operations: [{ op: 'replace', path: 'active', value: true }] } })
  await h.api('me', strong, undefined, 401)
  const reactivated = await finish(await sign({ link: false, changes: { mfa: true } }))
  assert.equal((await h.api('me', reactivated)).id, member.id)
  await h.api('mfa.policy', owner, { scope: 'off' })

  // Pending links are SCIM-addressable reservations, never active members.
  const peerSigned = await sign({ who: peer, changes: { subject: 'synthetic-nectar-102' } })
  await finish(peerSigned)
  const peerRequest = await pending(peer)
  const waiting = await sign({ who: peer, changes: { subject: 'synthetic-nectar-102' } })
  await scim('/' + peerRequest.id, { method: 'DELETE', status: 204 })
  await h.api('sso.link.approve', owner, fields(peerRequest), 409)
  await finish(waiting, { status: 403 })
  await sign({ who: peer, changes: { subject: 'synthetic-nectar-102' }, status: 403 })
  await scim('/' + peerRequest.id, { method: 'PATCH', body: { Operations: [{ op: 'replace', path: 'active', value: true }] }, status: 409 })
  assert.equal((await h.api('me', peer.cookie)).id, peer.id, 'A reservation never transfers control of a native account to SCIM')

  const configPending = await sign({ who: peer, changes: { subject: 'synthetic-nectar-rotated' } })
  await finish(configPending)
  const configRequest = await pending(peer), configFlight = await sign({ who: peer, changes: { subject: 'synthetic-nectar-rotating-flight' } })
  const oldToken = configured.scim_token
  configured = await h.api('sso.configure', owner, { ...settings, revision: 1 })
  await h.api('sso.link.approve', owner, fields(configRequest), 409)
  await finish(configFlight, { status: 403 })
  await h.api('me', reactivated, undefined, 401)
  await scim('', { token: oldToken, status: 401 })
  const ended = await sign({ who: peer, changes: { subject: 'synthetic-nectar-ended' } })
  await finish(ended)
  const endedRequest = await pending(peer)
  await h.api('access.end', owner, { member: peer.id })
  await h.api('sso.link.approve', owner, fields(endedRequest), 409)
  await h.api('access.give', owner, { email: peer.email, name: 'Nectar member restored', role: 'accountant' })
  peer.cookie = await h.signIn(peer.email)
  await h.api('sso.link.approve', owner, fields(endedRequest), 409)

  const expires = await sign({ who: peer, changes: { subject: 'synthetic-nectar-expired', authAge: 298000 } })
  await finish(expires)
  const expiringRequest = await pending(peer)
  await new Promise(resolve => setTimeout(resolve, 2200))
  await h.api('sso.link.approve', owner, fields(expiringRequest), 409)
  // Leave one live link proof and one active managed member for real archive proof.
  await finish(await sign({ who: peer, changes: { subject: 'synthetic-nectar-pending' } }))
  const retainedPending = await pending(peer)
  const finalSession = await finish(await sign({ link: false, changes: { mfa: true } }))
  await h.assertStorageExcludes([oldToken, configured.scim_token])
  console.log('Enterprise linking: dual control, exact owner consent, preserved attribution, atomic audit, replay, fresh factors, SCIM and stale-source refusals passed')
  return { pending: retainedPending, member, session: finalSession, ownerFactor: factor.secret, ownerAt: at }
}

// The real archive command must remove populated enterprise authority, while
// retaining ordinary member and audit history. Run only in a disposable tree.
export async function enterpriseLinkingArchive() {
  const { access, mkdir, mkdtemp, readFile, rm } = await import('node:fs/promises')
  const { join } = await import('node:path')
  const { readArchive } = await import('@runeditrun/rer/modules/portability')
  const { command } = await import('./cli.mjs')
  const { harness } = await import('./harness.mjs')
  assert.equal(process.env.NECTAR_TEST_CHECKOUT, '1', 'Only a disposable checkout may run archive restoration')
  const root = process.cwd()
  for (const name of ['.dev.vars', '.wrangler/state']) await access(join(root, name)).then(() => { throw new Error('A fresh unconfigured checkout is required') }, error => { if (error.code !== 'ENOENT') throw error })
  await mkdir(join(root, 'exports'), { recursive: true })
  const scratch = await mkdtemp(join(root, 'exports', 'enterprise-linking-'))
  let h
  try {
    const config = JSON.parse(await readFile('wrangler.jsonc', 'utf8'))
    const persistence = join(root, '.wrangler/state/v3'), databaseId = config.d1_databases.find(binding => binding.binding === 'DB').database_id
    await command(root, ['export', '--output', join(scratch, 'empty.rer')])
    h = await harness({ persistence, databaseId, applyMigrations: false })
    await h.raw('/auth/bootstrap', { body: { token: h.vars.SETUP_TOKEN, displayName: 'Nectar archive owner' } })
    const owner = await h.signIn(h.vars.OWNER_EMAIL)
    await h.raw('/setup', { cookie: owner, form: new URLSearchParams({ confirm: 'yes' }) })
    await h.api('business.configure', owner, { legal_name: 'Nectar archive journey', timezone: 'UTC', invoice_prefix: 'LINK', payment_terms_days: 30 })
    const result = await enterpriseLinkingFlow(h, owner), settings = { ...h.vars }
    const beforeMembers = await h.api('members', owner), beforeAudit = await h.api('audit', owner)
    assert.ok((await h.api('sso-links', owner)).some(row => row.id === result.pending.id))
    assert.equal((await h.api('me', result.session)).id, result.member.id)
    await h.close(); h = null
    const archive = join(scratch, 'populated.rer')
    await command(root, ['export', '--output', archive])
    const bytes = await readFile(archive), records = []
    for await (const record of readArchive(new ReadableStream({ start(controller) { controller.enqueue(bytes); controller.close() } }))) records.push(record)
    const items = records.filter(record => record.kind === 'part').flatMap(record => record.items)
    assert.ok(items.some(item => item.table === 'nc_members' && item.row.id === result.member.id), 'The populated archive preserves member attribution')
    assert.ok(items.some(item => item.table === 'nc_audit' && item.row.action === 'sso.link.approve'), 'Portable audit evidence remains present')
    assert.ok(!items.some(item => ['nc_sso_links', 'nc_scim_users', 'nc_sso_config', 'nc_saml_transactions'].includes(item.table)), 'No enterprise authority or pending proof enters the archive')
    await command(root, ['reset', '--yes'])
    await command(root, ['import', '--input', archive, '--yes'])
    h = await harness({ persistence, databaseId, applyMigrations: false, settings })
    assert.equal((await h.raw('/sso/start')).status, 404, 'Restoration requires fresh owner connection authorization')
    assert.equal((await h.raw('/scim/v2/Users')).status, 401)
    await h.api('me', result.session, undefined, 401)
    await h.raw('/auth/bootstrap', { body: { token: h.vars.SETUP_TOKEN, displayName: 'Nectar restored owner' } })
    const restoredOwner = await h.signIn(h.vars.OWNER_EMAIL)
    await h.raw('/setup', { cookie: restoredOwner, form: new URLSearchParams({ confirm: 'yes' }) })
    assert.deepEqual(await h.api('sso-links', restoredOwner), [], 'Pending links cannot be approved after restore')
    const restoredMembers = await h.api('members', restoredOwner)
    for (const member of beforeMembers.filter(row => row.role !== 'owner')) assert.deepEqual(restoredMembers.find(row => row.id === member.id), member)
    const restoredAudit = await h.api('audit', restoredOwner)
    assert.deepEqual(restoredAudit.filter(row => row.seq <= beforeAudit[0].seq), beforeAudit, 'Restoration preserves historical attribution')
    console.log('Enterprise linking archive: real export and restore preserve attribution without enterprise sessions, bindings, configuration or pending authority')
  } finally { await h?.close(); await rm(scratch, { recursive: true, force: true }) }
}

if (process.argv[1]?.endsWith('/enterprise-linking.mjs') && process.argv[2] === 'archive') await enterpriseLinkingArchive()
