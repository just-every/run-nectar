import { populateErasureKinds } from './erasure-record-kinds.mjs'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { file } from './harness.mjs'

// GOV-005: real request, verification, approval and financial-removal doors.
export async function erasureFlow(h, owner, onState = async () => {}) {
  await h.advanceClock('2026-02-01T16:00:00Z')
  const invite = async (email, role) => {
    await h.api('access.give', owner, { email, role, name: `Erasure ${role}` })
    return h.signIn(email, { requested: true })
  }
  const finance = await invite('gov005-finance@example.test', 'finance')
  const accountant = await invite('gov005-accountant@example.test', 'accountant')
  const agent = { bearer: (await h.api('credential.issue', owner, { name: 'Erasure preparation reader', scopes: ['prepare'] })).key }
  const makeCustomer = async (suffix, language = 'en') => (await h.api('customer.create', owner, {
    external_id: `GOV005-${suffix}`, name: `Marigold ${suffix} Legal LLC`, billing_email: `${suffix.toLowerCase()}@gov005.example`, address: `Private address ${suffix}`, language,
  })).id
  const customer = await makeCustomer('FORMER')
  const unrelated = await makeCustomer('OTHER')
  const privateValues = ['former@gov005.example', 'Private address FORMER', 'GOV005-FORMER', 'Elena Contactprivate', 'elena.contactprivate@gov005.example', 'private-note-GOV005', 'private-meta-GOV005', 'private-payment-GOV005', 'private-charge-GOV005']
  await h.api('contact.add', owner, { customer, name: privateValues[3], email: privateValues[4], role: 'billing' })
  await h.api('note.add', owner, { kind: 'customer', record: customer, body: privateValues[5] })
  await h.api('metadata.write', owner, { kind: 'customer', record: customer, revision: 0, metadata: { personal: privateValues[6] } })
  const charge = (await h.api('charge.add', owner, { customer, amount: '120', description: privateValues[8], taxable: false, effective_date: '2026-01-05' })).charge
  const invoice = (await h.api('invoice.manual', owner, { customer, charges: [charge], service_date: '2026-01-05' })).id
  await h.api('invoice.approve', owner, { invoice, acknowledge: true })
  await h.api('invoice.finalise', owner, { invoice, issue_date: '2026-01-05' })
  const payment = (await h.api('payment.record', owner, { customer, amount: '120', received_on: '2026-01-20', method: 'bank_transfer', reference: privateValues[7], evidence: privateValues[4] })).payment
  await h.api('payment.allocate', owner, { payment, invoice, amount: '120' })
  await h.api('note.add', owner, { kind: 'invoice', record: invoice, body: privateValues[5] })
  await h.api('metadata.write', owner, { kind: 'invoice', record: invoice, revision: 0, metadata: { personal: privateValues[6] } })
  const peerCharge=(await h.api('charge.add',owner,{customer:unrelated,amount:'37',description:'Other customer service',taxable:false,effective_date:'2026-01-05'})).charge
  const peerInvoice=(await h.api('invoice.manual',owner,{customer:unrelated,charges:[peerCharge],service_date:'2026-01-05'})).id
  await h.api('invoice.approve',owner,{invoice:peerInvoice,acknowledge:true})
  await h.api('invoice.finalise',owner,{invoice:peerInvoice,issue_date:'2026-01-05'})
  const rich=await populateErasureKinds(h,owner,customer)
  privateValues.push(...rich.privateValues)
  const unrelatedBefore=await h.api(`customers/${unrelated}`,owner)
  const frozenBefore=await h.api(`report-deliveries/${rich.report}`,owner)
  const originalInvoice = await h.api(`invoices/${invoice}`, owner)
  const originalCustomer = await h.api(`customers/${customer}`, owner)

  await h.api('erasures', null, undefined, 401)
  await h.api('erasures', agent, undefined, 403)
  await h.api('erasures', accountant)
  for (const who of [accountant, agent]) await h.api('erasure.request', who, { customer }, 403)
  const requestedMailCount = h.mails.length
  const redirect = await h.submit('erasure.request', finance, { customer,claimed_email:'unconfirmed-request@gov005.example' }, '/app/erasures')
  assert.equal(redirect.searchParams.has('error'), false, 'GOV-005 finance can record a request through the form door')
  const requests = await h.api('erasures', owner)
  const request = requests.find(row => row.customer_id === customer)
  assert.ok(request)
  assert.equal(request.status, 'pending')
  assert.equal(request.claimed_email,'unconfirmed-request@gov005.example')
  const message = h.mails.slice(requestedMailCount).find(mail => [mail.to].flat().includes(privateValues[0]))
  assert.ok(message, 'GOV-005 verification is sent to the billing email on file')
  assert.deepEqual(message.to, [privateValues[0]])
  assert.ok(!h.mails.slice(requestedMailCount).some(m=>[m.to].flat().includes('unconfirmed-request@gov005.example')),'GOV-005 claimed sender never receives the verification')
  const linkOf = mail => new URL(`${mail.text ?? ''} ${mail.html ?? ''}`.match(/https?:\/\/[^\s"<]+\/erase\/[a-f0-9]{64}/)[0]).pathname
  const path = linkOf(message)
  assert.ok(!JSON.stringify(requests).includes(path), 'GOV-005 request reports do not expose bearer links')
  await h.api('erasure.approve', owner, { request: request.id, confirm: true }, 409)
  assert.deepEqual(await h.api(`customers/${customer}`, owner), originalCustomer, 'GOV-005 unverified requests change no customer records')
  assert.equal((await h.raw(path)).status, 200)
  assert.equal((await h.raw(path,{method:'HEAD'})).status,200,'GOV-005 HEAD confirmation is read-only')
  assert.deepEqual(await h.api('erasures', owner), requests, 'GOV-005 GET confirmation is read-only')
  await onState({ h, owner, customer, request: request.id, path, label: 'confirmation' })
  for (const origin of ['https://attacker.example', '']) assert.equal((await h.raw(path, { form: new URLSearchParams({ confirm: 'yes' }), headers: { origin } })).status, 403)
  assert.equal((await h.raw(path, { form: new URLSearchParams({ confirm: 'no' }) })).status, 400)
  assert.equal((await h.raw(path, { form: new URLSearchParams({ confirm: 'yes' }) })).status, 200)
  assert.equal((await h.raw(path, { form: new URLSearchParams({ confirm: 'yes' }) })).status, 404, 'GOV-005 confirmation token is single-use')
  assert.equal((await h.api('erasures', owner)).find(row => row.id === request.id).verified_method, 'billing-email')
  assert.deepEqual(await h.api(`customers/${customer}`, owner), originalCustomer, 'GOV-005 verification itself erases nothing')
  for (const who of [finance, accountant, agent]) {
    await h.api('erasure.approve', who, { request: request.id, confirm: true }, 403)
    await h.api('erasure.verify', who, { request: request.id, reason: 'Identity checked', evidence: file('identity.txt', 'Evidence') }, 403)
    await h.api('erasure.purge', who, {}, 403)
  }
  const forbiddenForm = await h.raw('/app/do/erasure.approve', { cookie: finance, form: new URLSearchParams({ request: request.id, confirm: 'yes', returnTo: '/app/erasures' }) })
  assert.equal(forbiddenForm.status, 303)
  assert.ok(new URL(forbiddenForm.headers.get('location'), h.origin).searchParams.has('error'), 'GOV-005 the finance form cannot approve either')
  await h.api('erasure.approve', owner, { request: request.id }, 400)
  await onState({ h, owner, customer, request: request.id, path: '/app/erasures', label: 'verified' })
  const decisions=await Promise.all([1,2].map(()=>h.raw('/api/nectar/erasure.approve',{cookie:owner,body:{request:request.id,confirm:true}})))
  assert.deepEqual(decisions.map(r=>r.status).sort(),[200,409],'GOV-005 concurrent owner approvals commit exactly one erasure and receipt')
  const approved=await decisions.find(r=>r.status===200).json()
  await h.api('erasure.approve', owner, { request: request.id, confirm: true }, 409)
  assert.ok(approved.receipt.changed.some(row => row.kind === 'nc_customers' && row.fields.includes('billing_email') && row.records === 1))
  for (const kind of ['nc_contacts', 'nc_notes', 'nc_metadata_revisions', 'nc_payments', 'nc_invoice_lines']) assert.ok(approved.receipt.changed.some(row => row.kind === kind && row.records > 0), `GOV-005 receipt enumerates changed ${kind}`)
  for(const kind of rich.receiptKinds) assert.ok(approved.receipt.changed.some(row=>row.kind===kind),`GOV-005 populated ${kind} is on receipt`)
  assert.ok(approved.receipt.importCustody.receiptId,'GOV-005 native and source-custody receipts are bound atomically')
  assert.ok(approved.receipt.importCustody.stores)
  assert.equal(approved.receipt.verification.method, 'billing-email')
  assert.equal(approved.receipt.retained.until, '2033-01-20', 'GOV-005 latest payment controls the seven-calendar-year financial retention')
  assert.equal((await h.api('erasures',owner)).find(r=>r.id===request.id).claimed_email,'','GOV-005 request source address is withdrawn too')
  const retainedInvoice = await h.api(`invoices/${invoice}`, owner)
  assert.equal(retainedInvoice.status, 'issued')
  for (const key of ['number', 'issue_date', 'subtotal_cents', 'tax_cents', 'total_cents', 'paidCents', 'balanceCents']) assert.equal(retainedInvoice[key], originalInvoice[key], `GOV-005 retains issued financial fact ${key}`)
  assert.equal(retainedInvoice.retainedFinancial.legal_name, 'Marigold FORMER Legal LLC')
  assert.equal(approved.receipt.retained.legalLabels.issueSnapshots,1,'GOV-005 newly issued documents retain the actual issue snapshot')
  assert.equal(approved.receipt.retained.legalLabels.legacyDisplayedLabels,0,'GOV-005 the receipt distinguishes current snapshots from legacy displayed labels')
  assert.equal(retainedInvoice.retainedFinancial.retain_until, '2033-01-20')
  const erasedCustomer = await h.api(`customers/${customer}`, owner)
  assert.notEqual(erasedCustomer.name, originalCustomer.name)
  for(const path of [`/app/subscriptions/${rich.subscription}`,`/app/proposals/${rich.sourceProposal}`]) await h.page(path,owner,410)
  assert.equal((await h.raw(rich.renewalPath)).status,404,'GOV-005 erasure revokes existing public customer links')
  await h.api(`proposals/${rich.sourceProposal}`,owner,undefined,410)
  const frozenAfter=await h.api(`report-deliveries/${rich.report}`,owner)
  assert.deepEqual(frozenAfter.reports.map(r=>[r.metric,r.totalCents]),frozenBefore.reports.map(r=>[r.metric,r.totalCents]),'GOV-005 shared report numbers stay unchanged')
  assert.ok(JSON.stringify(frozenAfter).includes('Marigold OTHER Legal LLC'),'GOV-005 shared reports preserve the unrelated customer')
  const projections = [frozenAfter,erasedCustomer, retainedInvoice, await h.api('customers', owner), await h.api('payments', owner), await h.api(`notes/customer/${customer}`, owner), await h.api(`metadata/customer/${customer}`, owner), await h.api(`metadata/invoice/${invoice}`, owner), await h.api('audit', owner)]
  for (const value of privateValues) for(const [index,projection] of projections.entries()) assert.ok(!JSON.stringify(projection).includes(value), `GOV-005 personal value removed from API projection ${index}: ${value}`)
  for (const screen of [`/app/customers/${customer}`, '/app/customers', '/app/audit', '/app/erasures']) {
    const html = (await h.page(screen, owner)).replaceAll('<wbr>', '')
    assert.ok(!html.includes('Marigold FORMER Legal LLC'), 'GOV-005 ordinary screens omit the retained legal identity')
    for (const value of privateValues) assert.ok(!html.includes(value), `GOV-005 ${screen} removes personal values`)
  }
  for (const kind of ['customers', 'invoices']) {
    const response = await h.raw(`/app/exports/${kind}.csv`, { cookie: accountant })
    assert.equal(response.status, 200)
    const csv = await response.text()
    for (const value of privateValues) assert.ok(!csv.includes(value), `GOV-005 ${kind} CSV removes personal values`)
  }
  assert.deepEqual(await h.api(`customers/${unrelated}`, owner), unrelatedBefore, 'GOV-005 unrelated customer remains byte-for-byte unchanged')
  assert.deepEqual((await h.api('erasure.purge', owner, {})).removed, [], 'GOV-005 financial evidence cannot expire early')
  await h.api('customer.update',owner,{customer,revision:erasedCustomer.revision,name:'Reintroduced name',billing_email:'revive@gov005.example'},409)
  await h.api('contact.add',owner,{customer,name:'Reintroduced contact',email:'revive@gov005.example'},409)
  await h.api('metadata.write',owner,{kind:'customer',record:customer,revision:1,metadata:{pii:'revive@gov005.example'}},409)
  const subsequentRun=await h.api('billrun.prepare',owner,{period:'2026-01'})
  assert.ok(!(await h.api(`runs/${subsequentRun.id}`,owner)).invoices.some(row=>row.customer_id===customer),'GOV-005 erased subscriptions never produce another invoice')
  const mailBeforeSweep=h.mails.length
  assert.equal((await h.raw(`/cdn-cgi/local/scheduled?time=${Date.parse('2026-02-02T16:00:00Z')}&cron=${encodeURIComponent('0 14 * * *')}`)).status,200)
  assert.ok(!h.mails.slice(mailBeforeSweep).some(mail=>[mail.to].flat().includes(privateValues[0])),'GOV-005 scheduled work never sends to an erased billing identity')
  await onState({ h, owner, customer, request: request.id, path: '/app/erasures', label: 'receipt' })

  // Expiry and stale recipient each fail closed before any verification.
  const expiring = await makeCustomer('EXPIRING')
  await h.api('erasure.request', owner, { customer: expiring })
  const expiredPath = linkOf(h.mails.at(-1))
  const stale = await makeCustomer('STALE')
  const staleRequest = await h.api('erasure.request', owner, { customer: stale })
  const stalePath = linkOf(h.mails.at(-1)), staleCustomer = await h.api(`customers/${stale}`, owner)
  await h.api('customer.update', owner, { customer: stale, revision: staleCustomer.revision, name: staleCustomer.name, billing_email: 'replacement@gov005.example', address: staleCustomer.address })
  assert.equal((await h.raw(stalePath, { form: new URLSearchParams({ confirm: 'yes' }) })).status, 404, 'GOV-005 changing the billing email invalidates its pending link')
  await h.api('erasure.approve', owner, { request: staleRequest.id, confirm: true }, 409)
  await h.advanceClock('2026-02-09T16:00:00Z')
  assert.equal((await h.raw(expiredPath)).status, 404)
  await onState({h,owner,customer:expiring,request:null,path:expiredPath,label:'expired-confirmation'})
  assert.equal((await h.raw(expiredPath, { form: new URLSearchParams({ confirm: 'yes' }) })).status, 404, 'GOV-005 the seven-day link expires')

  // Spanish customer confirmation and owner-only evidence through multipart.
  const alternate = await makeCustomer('ALTERNATE', 'es-US')
  const altCharge=(await h.api('charge.add',owner,{customer:alternate,amount:'25',description:'Independent service',taxable:false,effective_date:'2026-02-09'})).charge
  const altInvoice=(await h.api('invoice.manual',owner,{customer:alternate,charges:[altCharge],service_date:'2026-02-09'})).id
  await h.api('invoice.approve',owner,{invoice:altInvoice,acknowledge:true})
  await h.api('invoice.finalise',owner,{invoice:altInvoice,issue_date:'2026-02-09'})
  const creditReason='private-credit-GOV005'
  const altCredit=await h.api('credit.issue',owner,{invoice:altInvoice,amount:'5',reason:creditReason})
  const altBefore=await h.api(`invoices/${altInvoice}`,owner)
  const alt = await h.api('erasure.request', owner, { customer: alternate })
  const spanishMail = h.mails.at(-1), spanishPath = linkOf(spanishMail)
  assert.ok(spanishMail.text.includes('eliminación'))
  const spanishHtml = await h.page(spanishPath)
  assert.match(spanishHtml, /<html lang="es-US">/)
  assert.ok(spanishHtml.includes('eliminación'))
  await onState({h,owner,customer:alternate,request:alt.id,path:spanishPath,label:'spanish-confirmation'})
  const evidenceText = 'Signed identity-verification record GOV005. Owner compared independent account records.'
  const evidence = file('independent-verification.txt', evidenceText, 'text/plain')
  await h.api('erasure.verify', owner, { request: alt.id, evidence }, 400)
  await h.api('erasure.verify', owner, { request: alt.id, reason: 'Billing mailbox disputed; identity independently checked' }, 400)
  const multipart = new FormData()
  multipart.set('request', alt.id)
  multipart.set('reason', 'Billing mailbox disputed; identity independently checked')
  multipart.set('evidence', new File([evidenceText], evidence.filename, { type: 'text/plain' }))
  const verify = await h.raw('/api/nectar/erasure.verify', { cookie: owner, form: multipart })
  assert.equal(verify.status, 200)
  const verified = (await h.api('erasures', owner)).find(row => row.id === alt.id)
  assert.equal(verified.verified_method, 'owner-evidence')
  assert.equal(verified.evidence_sha256, createHash('sha256').update(evidenceText).digest('hex'))
  const evidencePath = `/app/erasures/${alt.id}/evidence`
  const downloaded = await h.raw(evidencePath, { cookie: owner })
  assert.equal(downloaded.status, 200)
  assert.equal(await downloaded.text(), evidenceText)
  for (const who of [finance, accountant]) assert.equal((await h.raw(evidencePath, { cookie: who })).status, 403)
  assert.equal((await h.raw(spanishPath, { form: new URLSearchParams({ confirm: 'yes' }) })).status, 404, 'GOV-005 owner verification consumes the former email token')
  const altApproved = await h.api('erasure.approve', owner, { request: alt.id, confirm: true })
  assert.equal(altApproved.receipt.retained.creditRecords,1,'GOV-005 credit notes retain their minimal financial custody too')
  assert.ok(altApproved.receipt.changed.some(r=>r.kind==='nc_credit_notes'),'GOV-005 credit personal text is enumerated in the receipt')
  const altAfter=await h.api(`invoices/${altInvoice}`,owner)
  assert.ok(!JSON.stringify(altAfter).includes(creditReason),'GOV-005 the credit reason is erased')
  assert.deepEqual(altAfter.credits.map(r=>[r.id,r.number,r.amount_cents,r.issued_at]),altBefore.credits.map(r=>[r.id,r.number,r.amount_cents,r.issued_at]),'GOV-005 credit identifiers, amounts and dates remain exact')
  assert.equal(altApproved.receipt.verification.method, 'owner-evidence')
  assert.equal(altApproved.receipt.verification.reason, verified.verification_reason)
  assert.equal(altApproved.receipt.verification.evidence.sha256, verified.evidence_sha256)
  assert.equal((await h.raw(evidencePath,{cookie:owner})).status,404,'GOV-005 approval withdraws alternate-verification file bytes')
  assert.equal(altApproved.receipt.verification.evidence.status,'verification file withdrawn after erasure')
  const audit = await h.api('audit', owner)
  assert.ok(audit.some(row => row.action === 'erasure.verify.alternative' && row.subject === alt.id), 'GOV-005 alternative verification remains audited')
  await onState({ h, owner, customer: alternate, request: alt.id, path: '/app/erasures', label: 'alternative-receipt' })

  await h.advanceClock('2033-01-19T16:00:00Z')
  assert.deepEqual((await h.api('erasure.purge', owner, {})).removed, [])
  await h.api(`invoices/${invoice}`, owner)
  await h.advanceClock('2033-01-20T16:00:00Z')
  assert.equal((await h.raw(`/cdn-cgi/local/scheduled?time=${Date.parse('2033-01-20T16:00:00Z')}&cron=${encodeURIComponent('0 14 * * *')}`)).status,200,'GOV-005 the daily sweep executes the owner-approved retention decision')
  await h.api(`invoices/${invoice}`, owner, undefined, 404)
  assert.ok(!(await h.api('payments', owner)).some(row => row.id === payment))
  const completed = (await h.api('erasures', owner)).find(row => row.id === request.id)
  const receipt = JSON.parse(completed.receipt_json)
  assert.ok(receipt.removal.retainedLegalIdentityRemoved)
  assert.ok(receipt.removal.records.some(row => row.kind === 'nc_invoices' && row.records > 0))
  assert.deepEqual((await h.api('erasure.purge', owner, {})).removed, [], 'GOV-005 repeated removal is harmless and produces no duplicate removal')
  assert.ok((await h.api('audit',owner)).some(row=>row.action==='erasure.financial.remove'&&row.subject===request.id),'GOV-005 the daily removal is audited against the original approved request')
  await h.api(`invoices/${altInvoice}`,owner)
  await h.advanceClock(`${altApproved.receipt.retained.until}T16:00:00Z`)
  assert.ok((await h.api('erasure.purge',owner,{})).removed.includes(alt.id),'GOV-005 the owner can manually remove a second due financial group')
  await h.api(`invoices/${altInvoice}`,owner,undefined,404)
  assert.ok(!(await h.api(`customers/${alternate}`,owner)).ledger.credits.some(r=>r.id===altCredit.credit),'GOV-005 due removal deletes retained credit notes too')
  await onState({ h, owner, customer, request: request.id, path: '/app/erasures', label: 'financial-removal' })
  console.log('GOV-005 verified owner erasure, alternative evidence, roles, personal-data removal and seven-year financial retention passed')
}
