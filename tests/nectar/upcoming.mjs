import assert from 'node:assert/strict'
import { applyPolicy } from './policy-helper.mjs'

// USE-006: the live preview shares exact billing inputs, then freezes at issue.
export async function upcomingFlow(h, owner) {
  const previous = await h.api('business', owner)
  assert.equal(previous.timezone, 'America/Los_Angeles', 'USE-006 fixture uses the declared Pacific business day')
  await applyPolicy(h, owner, 'tax.declare', { tax_jurisdiction: 'CA', tax_mode: 'flat_rate', tax_rate: '10', tax_note: 'Reviewed upcoming invoice example' })
  await h.api('tax.review', owner, { revision: (await h.api('business', owner)).revision })
  const customer = (await h.api('customer.create', owner, { external_id: 'USE006-LIVE', name: 'Alder Research', billing_email: 'ap@alder.example' })).id
  const other = (await h.api('customer.create', owner, { external_id: 'USE006-OTHER', name: 'Other Research', billing_email: 'ap@other-research.example' })).id
  const meter = (await h.api('meter.create', owner, { code: 'use006-events', name: 'Research events', unit_label: 'events' })).id
  const prices = []
  for (const [code, kind, amount] of [['base', 'flat', '100'], ['seats', 'seat', '20'], ['events', 'unit', '2']]) {
    const product = (await h.api('product.create', owner, { code: `use006-${code}`, name: `Research ${code}` })).id
    prices.push((await h.api('price.create', owner, { product, kind, unit_amount: amount, taxable: true, ...(kind === 'unit' ? { meter } : {}) })).id)
  }
  const subscription = (await h.api('subscription.create', owner, { customer, start_date: '2026-01-01', anchor_day: 1, price: prices, quantity: ['', '2', ''] })).id
  const approved = await h.api('amendment.propose', owner, { subscription, kind: 'fixed_credit', value: '10', effective_from: '2026-01-01', note: 'Launch credit', clause: 'One-time ten dollar launch credit' })
  await h.api('amendment.decide', owner, { amendment: approved.amendment, decision: 'approved' })
  const proposed = await h.api('amendment.propose', owner, { subscription, kind: 'fixed_credit', value: '30', effective_from: '2026-01-01', note: 'Unapproved request', clause: 'Requested credit pending review' })
  const rejected = await h.api('amendment.propose', owner, { subscription, kind: 'fixed_credit', value: '50', effective_from: '2026-01-01', note: 'Declined request', clause: 'Requested credit declined' })
  await h.api('amendment.decide', owner, { amendment: rejected.amendment, decision: 'rejected' })
  await h.api('charge.add', owner, { customer, subscription, amount: '25', description: 'Research onboarding', taxable: true, effective_date: '2026-01-05' })
  const endpoint = `subscriptions/${subscription}/upcoming`
  const january = `${endpoint}?period=2026-01`
  const read = () => h.api(january, owner)
  const submit = (event_id, quantity, occurred_at, target = 'USE006-LIVE') => h.api('usage.submit', owner, { events: [{ event_id, quantity, occurred_at, customer: target, meter: 'use006-events' }] })
  const empty = await read()
  assert.equal(empty.subscription, subscription)
  assert.equal(empty.customer, customer)
  assert.equal(empty.state, 'preview')
  assert.equal(empty.invoiceId, null)
  assert.deepEqual(empty.period, { start: '2026-01-01', end: '2026-02-01' })
  assert.equal(empty.timezone, previous.timezone)
  assert.ok(Number.isFinite(new Date(empty.generatedAt).getTime()))
  assert.deepEqual([empty.calculation.subtotalCents, empty.calculation.taxCents, empty.calculation.totalCents], [15500, 1550, 17050])
  assert.deepEqual(empty.credits.map(c => c.id), [approved.amendment])
  assert.equal(empty.credits[0].amountCents, 1000)
  assert.equal(empty.credits[0].appliesThisPeriod, true)
  assert.equal(empty.remainingContractCreditCents, 1000)
  assert.ok(!empty.calculation.inputs.amendments.some(a => [proposed.amendment, rejected.amendment].includes(a.id)))

  const emptyHtml = await h.page(`/app/subscriptions/${subscription}?preview_period=2026-01`, owner)
  assert.ok(emptyHtml.includes('$170.50') && emptyHtml.includes('$10.00'), 'USE-006 operator preview shows the same pending credit and total')

  const event = ['use006-a', '3.25', '2026-01-05T12:00:00-08:00']
  assert.equal((await submit(...event)).accepted, 1)
  const first = await read()
  assert.equal(Number(first.meters[0].quantity), 3.25)
  assert.deepEqual([first.calculation.subtotalCents, first.calculation.taxCents, first.calculation.totalCents], [16150, 1615, 17765])
  assert.notEqual(first.calculation.fingerprint, empty.calculation.fingerprint)
  assert.equal((await submit(...event)).duplicates, 1)
  assert.deepEqual((await read()).calculation, first.calculation, 'USE-006 replay does not change the calculation')
  await submit('use006-foreign', '900', '2026-01-05T12:00:00-08:00', 'USE006-OTHER')
  assert.deepEqual((await read()).calculation, first.calculation, 'USE-006 another customer cannot affect this preview')
  await submit('use006-b', '1.25', '2026-01-05T13:00:00-08:00')
  const second = await read()
  assert.equal(Number(second.meters[0].quantity), 4.5)
  assert.equal(second.meters[0].events, 2)
  assert.deepEqual([second.calculation.subtotalCents, second.calculation.taxCents, second.calculation.totalCents], [16400, 1640, 18040])
  const control = { customer, meter: 'use006-events', day: '2026-01-05', expected_count: 2, expected_quantity: '4.5' }
  await h.api('usage.control', owner, control)
  const matched = await read()
  assert.ok(!matched.calculation.exceptions.some(e => e.code === 'usage_reconciliation'))
  assert.notEqual(matched.calculation.fingerprint, second.calculation.fingerprint)
  await h.api('usage.control', owner, { ...control, expected_count: 3, expected_quantity: '5' })
  const mismatch = await read()
  assert.ok(mismatch.calculation.exceptions.some(e => e.code === 'usage_reconciliation'))
  assert.notEqual(mismatch.calculation.fingerprint, matched.calculation.fingerprint)
  await h.api('usage.control', owner, control)
  await submit('use006-start', '0.5', '2026-01-01T08:00:00Z')
  await submit('use006-end', '0.5', '2026-02-01T07:59:59Z')
  await submit('use006-next-period', '9', '2026-02-01T08:00:00Z')
  const final = await read()
  assert.equal(Number(final.meters[0].quantity), 5.5)
  assert.deepEqual([...final.meters[0].eventIds].sort(), ['use006-a', 'use006-b', 'use006-start', 'use006-end'].sort())
  assert.equal(Number(final.meters[0].lateQuantity), 0)
  assert.deepEqual([final.calculation.subtotalCents, final.calculation.taxCents, final.calculation.totalCents], [16600, 1660, 18260])
  const run = await h.api('billrun.prepare', owner, { period: '2026-01' })
  const invoiceId = (await h.api(`runs/${run.id}`, owner)).invoices.find(i => i.customer_id === customer).id
  const invoice = await h.api(`invoices/${invoiceId}`, owner)
  assert.deepEqual(final.calculation.inputs, invoice.calculation.inputs)
  assert.equal(final.calculation.fingerprint, invoice.source_fingerprint)
  assert.equal(final.calculation.version, invoice.calc_version)
  assert.deepEqual([final.calculation.subtotalCents, final.calculation.taxCents, final.calculation.totalCents], [invoice.subtotal_cents, invoice.tax_cents, invoice.total_cents])
  assert.deepEqual(final.calculation.lines, invoice.lines.map(line => ({ kind: line.kind, description: line.description, quantity: line.quantity, unitAmount: line.unit_amount, amountCents: line.amount_cents, taxable: !!line.taxable, priceId: line.price_id, meterId: line.meter_id, periodStart: line.period_start, periodEnd: line.period_end, evidence: line.evidence })))
  await h.api('invoice.approve', owner, { invoice: invoiceId, acknowledge: true })
  await h.api('invoice.finalise', owner, { invoice: invoiceId, issue_date: '2026-02-01' })
  const issued = await read()
  assert.equal(issued.state, 'issued')
  assert.equal(issued.invoiceId, invoiceId)
  assert.deepEqual(issued.calculation, final.calculation)
  assert.equal(issued.remainingContractCreditCents, 0)
  assert.deepEqual(issued.credits, [])
  await submit('use006-late-january', '1.75', '2026-01-15T12:00:00-08:00')
  assert.deepEqual((await read()).calculation, issued.calculation, 'USE-006 issued inputs remain frozen after late ingestion')
  const february = await h.api(`${endpoint}?period=2026-02`, owner)
  assert.equal(Number(february.meters[0].quantity), 9)
  assert.equal(Number(february.meters[0].lateQuantity), 1.75)
  assert.deepEqual(february.meters[0].lateEventIds, ['use006-late-january'])
  assert.equal(february.remainingContractCreditCents, 0)

  const current = await h.api(endpoint, owner)
  const localParts = Object.fromEntries(new Intl.DateTimeFormat('en-US', { timeZone: previous.timezone, year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(new Date()).filter(p => p.type !== 'literal').map(p => [p.type, p.value]))
  const localDay = `${localParts.year}-${localParts.month}-${localParts.day}`
  assert.equal(current.period.start, `${localDay.slice(0, 7)}-01`)
  const nextMonth = new Date(`${current.period.start}T12:00:00Z`)
  nextMonth.setUTCMonth(nextMonth.getUTCMonth() + 1)
  assert.equal(current.period.end, nextMonth.toISOString().slice(0, 10))
  await submit('use006-current', '0.75', `${current.period.start}T12:00:00-08:00`)
  const streamed = await h.api(endpoint, owner)
  assert.equal(Number(streamed.meters[0].quantity), Number(current.meters[0].quantity) + 0.75)
  assert.ok(streamed.meters[0].eventIds.includes('use006-current'))
  assert.notEqual(streamed.calculation.fingerprint, current.calculation.fingerprint)
  assert.deepEqual([streamed.calculation.subtotalCents,streamed.calculation.taxCents,streamed.calculation.totalCents],[16300,1630,17930])
  const liveHtml = await h.page(`/app/subscriptions/${subscription}`, owner)
  assert.ok(liveHtml.includes('0.75 events') && liveHtml.includes('$179.30'), 'USE-006 operator refresh immediately agrees with the live API')
  await h.api(`${endpoint}?period=2025-12`, owner, undefined, 409)
  assert.ok((await h.page(`/app/subscriptions/${subscription}?preview_period=2025-12`, owner)).includes('id="upcoming"'), 'USE-006 an inactive selected period preserves the subscription page')

  const anchoredSubscription = (await h.api('subscription.create', owner, { customer: other, start_date: '2026-01-15', anchor_day: 15, price: [prices[0]] })).id
  const anchored = await h.api(`subscriptions/${anchoredSubscription}/upcoming`, owner)
  const expectedAnchor = new Date(`${localDay.slice(0, 7)}-15T12:00:00Z`)
  if (Number(localParts.day) < 15) expectedAnchor.setUTCMonth(expectedAnchor.getUTCMonth() - 1)
  assert.equal(anchored.period.start, expectedAnchor.toISOString().slice(0, 10), 'USE-006 default uses the subscription anchor in the business timezone')
  expectedAnchor.setUTCMonth(expectedAnchor.getUTCMonth() + 1)
  assert.equal(anchored.period.end, expectedAnchor.toISOString().slice(0, 10))
  assert.deepEqual((await h.api(`subscriptions/${anchoredSubscription}/upcoming?period=2026-01`, owner)).period, { start: '2026-01-15', end: '2026-02-15' })

  await h.api('access.give', owner, { email: 'upcoming-accountant@example.test', name: 'Upcoming Accountant', role: 'accountant' })
  const accountant = await h.signIn('upcoming-accountant@example.test', { requested: true })
  const prepareKey = await h.api('credential.issue', owner, { name: 'Upcoming preparation', scopes: ['prepare'] })
  const usageKey = await h.api('credential.issue', owner, { name: 'Upcoming ingestion', scopes: ['usage'] })
  for (const who of [accountant, { bearer: prepareKey.key }])
    assert.deepEqual((await h.api(january, who)).calculation, issued.calculation)
  await h.api(january, { bearer: usageKey.key }, undefined, 403)
  await h.api(january, undefined, undefined, 401)
  await h.api('subscriptions/missing/upcoming?period=2026-01', owner, undefined, 404)
  for (const period of ['2026-13', '2026-00', '2026-1', 'nonsense'])
    await h.api(`${endpoint}?period=${period}`, owner, undefined, 400)
  const path = `/app/subscriptions/${subscription}?preview_period=2026-01`
  const html = await h.page(path, accountant)
  assert.match(html, /id="upcoming"/)
  assert.match(html, /182\.60/)
  const usageHtml = await h.page('/app/usage?period=2026-01', owner)
  assert.ok(usageHtml.includes(`/app/subscriptions/${subscription}`) && usageHtml.includes('#upcoming'))
  await h.api('credential.revoke', owner, { key: prepareKey.id })
  await h.api('credential.revoke', owner, { key: usageKey.id })
  await applyPolicy(h, owner, 'tax.declare', { tax_jurisdiction: previous.tax_jurisdiction, tax_mode: previous.tax_mode, tax_rate: previous.tax_rate, tax_note: previous.tax_note })
  await h.api('tax.review', owner, { revision: (await h.api('business', owner)).revision })
  console.log('USE-006 live usage, exact upcoming calculation, contract credits, timezone boundaries and frozen issued preview passed')
  return { subscription, customer, invoiceId, paths: [path, `/app/subscriptions/${subscription}`, '/app/usage?period=2026-01'] }
}
